"""
Training Configuration.

Split of responsibilities:
  - `schema.py`  — everything derived from the GAME (enemy tables, wave
                   templates, curriculum, feature layout, decoder constants).
                   Generated by `npm run ai-schema`, never hand-edited.
  - this file    — everything that is a TRAINING choice (hyperparameters,
                   reward shaping, episode length, checkpointing).

Architecture:
  - State:  schema.INPUT_SIZE features (162 at schema v2)
  - Action: template_idx (32 slots) + 4 continuous factors in [0,1]
  - Reward: 4 terms (DEATH, DRAMA, SWARM_SIZE, PROGRESSION)
"""

