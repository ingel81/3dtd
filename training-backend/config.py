# === SERVER ===
SERVER_HOST = "localhost"
SERVER_PORT = 3001
DASHBOARD_PORT = 3002

# === ACTION SPACE ===
NUM_CONTINUOUS = 4
OUTPUT_SIZE = MAX_TEMPLATE_SLOTS + NUM_CONTINUOUS  # 36

# Ordered names of the continuous params (for logging + debugging).
CONTINUOUS_PARAM_NAMES = ["count", "spawn_delay", "hp_mult", "variation"]

# === TRAINING ===
# Lowered from 3e-4 after the death-outlier fix failed to bring approx-KL down.
# Measured at 3e-4: KL 0.23-0.37 against a 0.02 target, i.e. a SINGLE minibatch
# step moved the policy more than ten times the intended amount, so the
# per-minibatch early stop fired after the first one on every update. That is a
# sixteenth of the configured learning (4 epochs x 4 minibatches), and it showed
# in the policy: after 21 updates the continuous factors still sat at their
# initial 0.5 +/- 0.14 with log_std unmoved.
#
# KL grows roughly with the square of the step, so a third of the rate should
# land near 0.04. Lower rate, but far more of each batch is actually used.
LEARNING_RATE = 0.0001
CLIP_EPSILON = 0.2
VALUE_COEF = 0.5

# Batch raised from 16. Sixteen samples of a reward that ranges roughly -30..+2,
# drawn from four clients contributing consecutive correlated waves, gave a
# gradient direction that was mostly noise — and during the curriculum (waves
# 1-30, where the mask has a single option) the categorical head gets no signal
# at all while still filling batch slots. At timescale 75 with four clients this
# is a couple of minutes of wall time.
BATCH_SIZE = 128
# Raised from 32. The per-minibatch KL stop fires on the first minibatch of
# nearly every update (approx-KL 0.14-0.20 against a 0.02 target), so at 32 only
# a quarter of each collected batch was ever used and three quarters were thrown
# away. A bigger minibatch is the conservative fix: averaging over more samples
# cuts gradient variance, which lowers the KL of each step directly, rather than
# loosening TARGET_KL and simply permitting larger jumps. At 64 a single
# surviving step already covers half the batch.
MINIBATCH_SIZE = 64
UPDATE_EPOCHS = 4

# Stop the epoch loop early once the policy has moved too far from the one that
# collected the data. Four epochs over the same samples with no KL guard is how
# PPO quietly turns into an unclipped policy-gradient step.
TARGET_KL = 0.02

# Entropy bonus on the template head only.
#
# The continuous entropy term was measured on the pre-sigmoid Gaussian, so
# maximising it simply pushed `log_std` up — and a wide Gaussian squashed
# through a sigmoid piles mass on the range ENDPOINTS. That is anti-exploration
# in factor space: waves collapse to min/max count and min/max HP, which is the
# opposite of the "varied waves" goal. `log_std` is clamped instead (see
# model.py) and only the categorical head keeps a bonus.
ENTROPY_COEF = 0.02

# Effective window for the reward-scaling statistic. A lifetime count would
# stop adapting once it grew large, which is wrong for a reward that keeps
# shifting as the policy improves and the wave numbers climb.
REWARD_SCALE_WINDOW = 2000

# How many waves a single client may accumulate before its trajectory is cut
# and bootstrapped. Long survivors would otherwise contribute nothing.
TRAJECTORY_FLUSH_LENGTH = 32

# Run one client deterministically every N episodes so the metrics describe the
# policy we actually export, not the exploration noise around it.
DETERMINISTIC_EVAL_EVERY = 25

# Waves are NOT independent, and treating them as such inverted the objective.
#
# The player never heals (`healBase()` has no production caller), so HP is a
# one-way resource across a whole run. The per-wave optimum requires 1-5% HP
# loss, which at ~3% per wave kills the player in ~33 waves — and the old
# bandit framing paid the full sweet-spot reward the entire way down, charging
# only a single -3.5 at the end. "Bleed the player out and kill them at wave 30"
# scored ~+83 and beat every sustainable policy. That is why runs died at waves
# 5, 10 and 11 with the reward curve still climbing.
#
# Returns are now discounted along each client's trajectory, so the waves that
# set up a death are charged for it.
GAMMA = 0.9

# Generalised advantage estimation. 0.95 is the usual compromise between the
# bias of pure bootstrapping and the variance of full Monte-Carlo returns.
GAE_LAMBDA = 0.95

# === REWARD — Term 1: DEATH ===
# === FAIRNESS GATE — closed-loop calibration ===
#
# FAIRNESS_KILL_REALISM (in the generated schema) was measured on waves 1-10,
# where defenses kill 64% of what the DPS model predicts. From wave 11 they kill
# 100%. Applying one discount to both regimes capped waves at 5-14 enemies
# against a 6700-DPS defense, which put the reward's near-miss target outside
# the action space entirely: every count_factor shipped the same ~20 enemies and
# all of them died, so the expected policy gradient for that dimension was zero
# and it never left its initialisation.
#
# Instead of a second hand-tuned constant, steer the cap from what the defense
# actually achieves. It re-calibrates itself when the bot gets better or worse,
# and it will hold for a human player too.
GATE_ADAPT_WINDOW = 8          # waves of kill-share history before steering
GATE_SATURATED_SHARE = 0.98    # "the defense killed everything" threshold
GATE_MULT_UP = 1.15            # saturated -> allow bigger waves
GATE_MULT_DOWN = 0.80          # the run ended -> back off hard
GATE_MULT_MIN = 0.5
GATE_MULT_MAX = 40.0           # generous: the cap can be off by an order of magnitude

# === REWARD v4 ================================================================
#
# v3 expressed the design goal as "the player should lose 1-5% of max HP every
# wave". Measured over ~9900 episodes that turned out to be unreachable and
# self-contradictory, and the agent correctly responded by doing nothing:
#
#   - Leak damage is `1 + floor((w-1)/10)` HP against 100 max HP, so damage is
#     QUANTISED. From wave 51 a single leak costs 6% and zero leaks cost 0%.
#     No value inside [1%, 5%] exists. Three of the four terms gated on that
#     band, so from W51 they were structurally dead.
#   - The player never heals (`healBase()` has only test callers, no research
#     restores lives) and the game has no win condition. 100 HP is the budget
#     for the entire run, so "1-5% every wave" IS death within 100 waves — the
#     very thing the DEATH term punished with -15..-30.
#   - Drama was read off `avg_progress`, the MEAN path progress. Drama lives in
#     the upper tail: 270 rats of which 5 reach 95% is tense, and the mean
#     reports 0.1. `near_miss_ratio` was already computed and thrown away.
#
# v4 therefore splits the two questions that v3 conflated:
#
#   DRAMA  — "was this wave exciting?"  Measured per wave on near_miss_ratio,
#            a fine-grained (step 1/count) upper-tail statistic.
#   PACING — "is the run the right length?"  Measured against an HP decay curve
#            across the whole run, where a 6-HP leak is a small step instead of
#            a jump across a band.
#
# === REWARD — Term 1: DEATH ===
# Relative to the target curve, not absolute. The run is SUPPOSED to end: an
# endless game with no healing has exactly one ending. Dying on schedule is
# free; dying at wave 10 is not. This removes v3's contradiction, where the
# reward's own optimum was an outcome the reward also punished.
TARGET_RUN_WAVES = 80             # the HP curve is drawn to hit zero here
# Cost of dying at wave 0, falling quadratically to 0.0 at TARGET_RUN_WAVES.
#
# Bounded from BELOW by the exploit it exists to kill: a death must outweigh the
# good waves that set it up, or "bleed them out, then cash in" wins again (it
# did, under v3's -3.5 cap). Ten waves at the +1.3 peak, discounted at GAMMA,
# is 8.47 — so a death around wave 15 has to cost more than that.
#
# Bounded from ABOVE by the reward scaler. Rewards are normalised by a windowed
# std, and deaths are rare and huge, so THEY set that std and everything else
# gets divided into noise. Measured at -40 over 1304 steps: surviving waves had
# mean -0.50 and std 0.40, deaths mean -32.7 at an 8.7% rate, and the combined
# std was 9.13 — of which the death term contributed 9.12. A full drama swing
# of 1.30 came out at 0.142 after scaling while a death came out at -3.58, a
# 25:1 ratio. At that ratio the agent is not learning to build good waves, it
# is learning to avoid deaths, which is how v3 collapsed.
#
# Lowered again to -8 after the run collapsed to zero drama over 56 updates.
# The per-wave arithmetic explains it: at -15 and a 9% death rate, expected
# death cost is ~0.7 per wave against a drama span of only 1.3 (from -0.3 idle
# to +1.0 peak), so pushing never paid and near-miss fell monotonically
# 0.104 -> 0.082 -> 0.058 -> 0.042 -> 0.017 -> 0.000.
#
# The bleed-them-out exploit stays dead because DEATH is not the only thing
# opposing it. Killing a player inside ~15 waves means running far below the HP
# curve the whole way, which accumulates roughly -10 of PACING before the death
# is even collected. The reward test now checks that combined cost rather than
# the death term alone, which is what forced the earlier, oversized values.
REWARD_DEATH_MAX = -8.0

# === REWARD — Term 2: DRAMA (near-miss distribution) ===
# Target a BAND of the fraction of enemies that get past 80% of the path.
# 0.25 means: a quarter of the wave nearly makes it. Zero is a walkover, 1.0 is
# a breach. A Gaussian, not a step: every wave gets a gradient telling it which
# way to move, which is what v3's cliff-shaped gates destroyed.
# Measured over 4002 waves spanning several policies: p50 0.000, p75 0.165,
# p90 0.200, p95 0.217, p99 0.375, max 0.667. A target of 0.25 sat at the 97th
# percentile — reachable in principle, never in practice, so the peak was
# decoration and the policy optimised the reachable slope beside it. That is v3's
# unreachable-band failure in a milder form. 0.20 is the 90th percentile:
# demanding, and actually hit.
NEAR_MISS_TARGET = 0.20
NEAR_MISS_SIGMA = 0.18
REWARD_DRAMA_PEAK = 1.00          # value at exactly NEAR_MISS_TARGET
REWARD_DRAMA_IDLE = -0.30         # value as near_miss_ratio -> far from target
# A ratio is scale-free, so 1 leaker out of 4 would score as well as 25 out of
# 100. Damp small waves so the band cannot be farmed with a handful of enemies.
# Boss templates start at countRange [10,100], so full credit at 40 is reachable
# for every template in the set.
# Below this a wave gets no positive drama at all, and from here it ramps
# LINEARLY to full credit at DRAMA_FULL_COUNT. sqrt-damping alone relocated the
# exploit instead of closing it: 5 near-missers out of 21 enemies scored
# bell~0.99 x sqrt(21/40) = +0.71 per wave at no risk, and 48% of observed waves
# came in at 20 enemies or fewer. Nothing in the function pushed size upward.
# Lowered from 20 together with the leak-budget gate. That gate now caps early
# waves at 16-23 enemies, because that is what a two-to-five-tower defense can
# actually fight; at a floor of 20 the agent could not earn positive drama at
# all through the opening waves, which is where 85% of runs are decided. The
# floor still blocks what it was built for — one near-misser out of four.
DRAMA_MIN_COUNT = 10
# Waves that actually reach the target band have a median count of 30; waves
# below 0.05 near-miss have a median of 39. Near-misses come from a FEW TOUGH
# enemies surviving the gauntlet, not from mass — a big rat swarm gets shredded
# early and scores a low ratio. Full credit at 40 therefore halved the reward
# exactly where the behaviour we want originates. The floor at 20 still blocks
# the farming case (one near-misser out of four).
DRAMA_FULL_COUNT = 20

# Leaks are charged inside DRAMA, as a slope on the fraction of the wave that
# reached the base. This replaces the old overflow guard, which tested
# `avg_progress > 0.95` — the MEAN, the very statistic v4 rejected for drama.
# A catastrophic wave leaking 40% of its enemies has a mean around 0.6 and
# sailed straight past that guard.
# Kept deliberately mild, because a leak is already charged twice elsewhere:
# it drops the player off the PACING curve, and enough of them reach DEATH.
# This slope exists only so a breach cannot read as drama, not as a third
# punishment for the same event — pricing it like one recreates v3's mistake of
# mixing "was it exciting" with "was it too much" in a single term.
#
# The measured ratio decides the magnitude. Over 3912 waves, estimated
# leak_ratio averaged 0.223 against a near_miss_ratio of 0.071, and among waves
# that nearly reached the target band leaks ran at 0.296 — roughly two leaks per
# near-miss, because an enemy that survives the kill zone usually goes all the
# way. At -2.0 that arithmetic left a near-target wave at +0.08 instead of
# +0.675, so attempting drama barely paid at all.
REWARD_LEAK_SLOPE = -0.8

# Dense shaping on the upper tail of path progress.
#
# 88-91% of waves have a near-miss ratio of exactly 0, and across that whole
# region DRAMA is a constant — the gradient toward "push harder" is zero even
# when the gate is open. This pays a little for every wave that gets the horde
# further, so the agent can climb from "everything dies at 40% of the path" to
# "everything dies at 79%" and be told it is improving, long before the first
# near-miss exists. Kept well under the drama peak so it stays a tiebreaker and
# cannot be farmed on its own; p90 rather than the mean, for the same reason
# drama uses the tail.
REWARD_P90_PROGRESS_WEIGHT = 0.12

# PACING tail. A pure Gaussian saturates: beyond ~2 sigma the bell is flat and
# the term becomes a constant tax with NO gradient. Measured: 58.4% of waves sat
# at exactly -0.60, i.e. the term that is supposed to steer the run length was
# dead on the majority of waves — precisely the ones furthest off the curve.
# Quadratic inside 1 sigma for fine control, linear beyond it so the gradient
# survives where it is actually needed.
# The tail must stay gentle AND stay long. A first attempt used slope 0.5 with
# a cap at 2.0, which merely moved the flat spot: the cap binds at 3 sigma, and
# measured 69% of waves sat on it because runs were ending far off the curve.
# A shallower slope with a much later cap keeps a live gradient out to ~6 sigma
# without letting the term outweigh DRAMA in the range that actually occurs.
PACING_TAIL_SLOPE = 0.3
PACING_SHAPE_CAP = 5.0

# A wipe is a wipe whenever it lands. The shortfall term alone falls to -0.6 by
# wave 70 and -0.006 by wave 79, so deleting a healthy player in one wave was
# free there — the exact "unfair wipe" this whole design is meant to exclude.
OVERKILL_DAMAGE_FRACTION = 0.25
REWARD_OVERKILL = -3.0

# === REWARD — Term 3: PACING (HP decay curve) ===
# Where the player's HP should be by now, and how sharply we insist on it.
# At 100 HP and TARGET_RUN_WAVES=80 the curve asks for ~1.25 HP per wave, which
# past W51 means one leak every four to five waves — coarse, but steerable via
# count and spawn delay, unlike the old per-wave band.
PACING_SIGMA = 0.18               # in HP fraction; ~18 HP of tolerance
# Magnitude of the PENALTY for being off the curve; 0 when exactly on it.
# Deliberately not a bonus: paying for being on schedule meant a policy that
# sent nothing still scored positive whenever the player happened to sit on the
# curve, which is the v3 collapse re-entering through a different door.
REWARD_PACING_PEAK = 0.60

# === REWARD — Term 4: SWARM_SIZE ===
# Unchanged in spirit: a tiebreaker inside the drama envelope, never the goal.
# Now gated on drama being positive rather than on the dead damage band.
SWARM_SMALL_THRESHOLD = 20        # below this = tiny wave (penalty)
SWARM_SMALL_PENALTY = -0.10
SWARM_SIZE_SLOPE = 0.0004
SWARM_SIZE_CAP = 0.30             # below the drama peak by design

# === OVERFLOW — DISPLAY ONLY as of the leak-slope change ===
# The reward no longer guards overflow via mean path progress. That guard asked
# `avg_progress > 0.95` — the mean, the exact statistic v4 rejected for drama —
# and a wave leaking 40% of its enemies has a mean near 0.6 and passed it
# untouched. Breaches are now charged in DRAMA on REWARD_LEAK_SLOPE, against the
# measured fraction that actually reached the base. This threshold survives only
# to bucket the dashboard's progress histogram.
PROGRESS_OVERFLOW_THRESHOLD = 0.95

# === Damage bands — DISPLAY ONLY as of v4 ===
# No reward term gates on these any more. The dashboard still buckets waves by
# them (`damageSweetPct`, the damage-zone histogram) because "how much HP did
# that wave actually cost" stays the number a human wants to see.
DAMAGE_SWEET_MIN = 0.01
DAMAGE_SWEET_MAX = 0.05
DAMAGE_HARD_THRESHOLD = 0.20
PROGRESS_NEAR_MISS_LOW = 0.65     # still used by the progress histogram
PROGRESS_NEAR_MISS_HIGH = 0.90

